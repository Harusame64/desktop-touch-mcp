#!/usr/bin/env node
// internal #230 — writes src/tools/_emoji-variation-bases.ts from two of Unicode's emoji data files.
// The consent question for Windows Terminal must show what the shell receives, and these are the
// only places an invisible joiner or selector is drawn as part of an emoji (PR codex on #766):
// - emoji-variation-sequences.txt: the characters with a standardized text (VS15) and emoji (VS16)
//   style. A selector after anything else draws as nothing. Keycap bases (0-9 # *) are left out:
//   a keycap is VS16 + U+20E3, checked apart.
// - emoji-zwj-sequences.txt: the recognized ZWJ sequences. A joiner between two emoji that do not
//   form one (🐱‍🐶) draws as nothing and is still received.
//
//   curl -sSfLO https://www.unicode.org/Public/latest/ucd/emoji/emoji-variation-sequences.txt
//   curl -sSfLO https://www.unicode.org/Public/emoji/latest/emoji-zwj-sequences.txt
//   node scripts/generate-emoji-variation-bases.mjs emoji-variation-sequences.txt emoji-zwj-sequences.txt
import { readFileSync, writeFileSync } from "node:fs";

const header = (src, key) => new RegExp(`^# ${key}: (.+)$`, "m").exec(src)?.[1] ?? "unknown";

const variation = readFileSync(process.argv[2], "utf8");
const bases = new Set();
for (const line of variation.split("\n")) {
  const m = /^([0-9A-F]{4,6}) FE0[EF]\s*;/.exec(line);
  if (m) bases.add(parseInt(m[1], 16));
}
for (const c of "0123456789#*") bases.delete(c.codePointAt(0));
const sorted = [...bases].sort((a, b) => a - b);
const ranges = [];
for (const cp of sorted) {
  const last = ranges[ranges.length - 1];
  if (last && last[1] === cp - 1) last[1] = cp;
  else ranges.push([cp, cp]);
}
const u = (cp) => `\\u{${cp.toString(16)}}`;
const cls = ranges.map(([a, b]) => (a === b ? u(a) : `${u(a)}-${u(b)}`)).join("");

const zwj = readFileSync(process.argv[3], "utf8");
const seqs = [];
for (const line of zwj.split("\n")) {
  const m = /^([0-9A-F ]+?)\s*;\s*RGI_Emoji_ZWJ_Sequence\s*;/.exec(line);
  if (m) seqs.push(m[1].trim().toLowerCase());
}
if (seqs.length === 0) throw new Error("no ZWJ sequences parsed");

const out = `// Generated by scripts/generate-emoji-variation-bases.mjs — do not edit by hand.
// Sources: emoji-variation-sequences.txt, Unicode ${header(variation, "Version")} (${header(variation, "Date")});
//          emoji-zwj-sequences.txt, Unicode ${header(zwj, "Version")} (${header(zwj, "Date")}).

/** The ${sorted.length} characters with a standardized text (VS15) and emoji (VS16) style, keycap bases left out. */
export const EMOJI_VARIATION_BASES = String.raw\`[${cls}]\`;

/** The ${seqs.length} recognized emoji ZWJ sequences, each as space-separated hex code points. */
export const EMOJI_ZWJ_SEQUENCES: readonly string[] = [
${seqs.map((s) => `  "${s}",`).join("\n")}
];
`;
writeFileSync(new URL("../src/tools/_emoji-variation-bases.ts", import.meta.url), out);
console.log(`${sorted.length} bases, ${seqs.length} ZWJ sequences`);
