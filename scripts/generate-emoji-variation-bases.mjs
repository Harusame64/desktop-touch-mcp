#!/usr/bin/env node
// internal #230 — writes src/tools/_emoji-variation-bases.ts from Unicode's
// emoji-variation-sequences.txt: the characters that have a standardized text (VS15) and emoji
// (VS16) style. The consent question for Windows Terminal lets a variation selector through only
// after one of these; after anything else it draws as nothing and the shell still receives it
// (PR codex on #766). Keycap bases (0-9 # *) are left out: a keycap is VS16 + U+20E3, checked apart.
//
//   curl -sSfLO https://www.unicode.org/Public/latest/ucd/emoji/emoji-variation-sequences.txt
//   node scripts/generate-emoji-variation-bases.mjs emoji-variation-sequences.txt
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(process.argv[2], "utf8");
const version = /^# Version: (.+)$/m.exec(src)?.[1] ?? "unknown";
const date = /^# Date: (.+)$/m.exec(src)?.[1] ?? "unknown";
const bases = new Set();
for (const line of src.split("\n")) {
  const m = /^([0-9A-F]{4,6}) FE0[EF]\s*;/.exec(line);
  if (m) bases.add(parseInt(m[1], 16));
}
for (const c of "0123456789#*") bases.delete(c.codePointAt(0));
const sorted = [...bases].sort((a, b) => a - b);
const ranges = [];
for (const cp of sorted) {
  const last = ranges[ranges.length - 1];
  if (last && last[1] === cp - 1) last[1] = cp;
  else ranges.push([cp, cp]);
}
const u = (cp) => `\\u{${cp.toString(16)}}`;
const cls = ranges.map(([a, b]) => (a === b ? u(a) : `${u(a)}-${u(b)}`)).join("");
const out = `// Generated by scripts/generate-emoji-variation-bases.mjs — do not edit by hand.
// Source: emoji-variation-sequences.txt, Unicode ${version} (${date}); ${sorted.length} bases.
// The characters with a standardized text (VS15) and emoji (VS16) style, keycap bases left out.
export const EMOJI_VARIATION_BASES = String.raw\`[${cls}]\`;
`;
writeFileSync(new URL("../src/tools/_emoji-variation-bases.ts", import.meta.url), out);
console.log(`${sorted.length} bases, ${ranges.length} ranges, Unicode ${version}`);
